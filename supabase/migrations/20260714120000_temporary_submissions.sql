-- Temporary submissions: admin-seeded photos so missions / club feed / team Social
-- do not look empty before real explorers submit.

CREATE TABLE IF NOT EXISTS public.temporary_submissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  activity_id bigint NOT NULL REFERENCES public.activities (id) ON DELETE CASCADE,
  display_name text NOT NULL,
  team_id bigint NOT NULL REFERENCES public.teams (id) ON DELETE RESTRICT,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  xp integer NOT NULL DEFAULT 0,
  team_xp_awarded integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS temporary_submissions_activity_id_idx
  ON public.temporary_submissions (activity_id);

CREATE INDEX IF NOT EXISTS temporary_submissions_team_id_idx
  ON public.temporary_submissions (team_id);

CREATE INDEX IF NOT EXISTS temporary_submissions_submitted_at_idx
  ON public.temporary_submissions (submitted_at DESC);

CREATE TABLE IF NOT EXISTS public.temporary_submission_photos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  temporary_submission_id bigint NOT NULL
    REFERENCES public.temporary_submissions (id) ON DELETE CASCADE,
  photo_url text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS temporary_submission_photos_submission_id_idx
  ON public.temporary_submission_photos (temporary_submission_id);

ALTER TABLE public.temporary_submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.temporary_submission_photos ENABLE ROW LEVEL SECURITY;

-- Authenticated clients can read seed content (mirrors approved club photos).
CREATE POLICY "Authenticated can read temporary submissions"
  ON public.temporary_submissions
  FOR SELECT TO authenticated
  USING (true);

CREATE POLICY "Authenticated can read temporary submission photos"
  ON public.temporary_submission_photos
  FOR SELECT TO authenticated
  USING (true);

