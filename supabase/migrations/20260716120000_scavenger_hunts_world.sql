CREATE OR REPLACE FUNCTION public.scavenger_assert_profile_owner(p_profile_id bigint)
RETURNS uuid
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_owner uuid;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  SELECT p.user_id INTO v_owner
  FROM public.profiles p
  WHERE p.id = p_profile_id;

  IF v_owner IS NULL THEN
    RAISE EXCEPTION 'Profile not found';
  END IF;

  IF v_owner <> v_uid THEN
    RAISE EXCEPTION 'Not authorized for this profile';
  END IF;

  RETURN v_uid;
END;
$$;

REVOKE ALL ON FUNCTION public.scavenger_assert_profile_owner(bigint) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.scavenger_assert_profile_owner(bigint) TO service_role;

CREATE OR REPLACE FUNCTION public.scavenger_distance_meters(
  p_lat1 double precision,
  p_lng1 double precision,
  p_lat2 double precision,
  p_lng2 double precision
)
RETURNS double precision
LANGUAGE sql
IMMUTABLE
SET search_path = public
AS $$
  SELECT 6371000.0 * 2.0 * asin(
    sqrt(
      power(sin(radians(p_lat2 - p_lat1) / 2.0), 2) +
      cos(radians(p_lat1)) * cos(radians(p_lat2)) *
      power(sin(radians(p_lng2 - p_lng1) / 2.0), 2)
    )
  );
$$;

REVOKE ALL ON FUNCTION public.scavenger_distance_meters(double precision, double precision, double precision, double precision)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.scavenger_distance_meters(double precision, double precision, double precision, double precision)
  TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.scavenger_get_lock_for_target(
  p_type text,
  p_item_id uuid
)
RETURNS public.huntly_quest_locks
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_lock_id uuid;
  v_lock public.huntly_quest_locks;
  v_published boolean;
  v_lockable boolean;
BEGIN
  IF p_type = 'quest' THEN
    SELECT q.lock_id, q.published, q.lockable
    INTO v_lock_id, v_published, v_lockable
    FROM public.huntly_quests q
    WHERE q.id = p_item_id;
  ELSIF p_type = 'questGroup' THEN
    SELECT g.lock_id, g.published, g.lockable
    INTO v_lock_id, v_published, v_lockable
    FROM public.huntly_quest_groups g
    WHERE g.id = p_item_id;
  ELSE
    RAISE EXCEPTION 'Invalid type: %', p_type;
  END IF;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Target not found';
  END IF;

  IF NOT coalesce(v_published, false) THEN
    RAISE EXCEPTION 'Target is not published';
  END IF;

  IF NOT coalesce(v_lockable, false) OR v_lock_id IS NULL THEN
    RETURN NULL;
  END IF;

  SELECT * INTO v_lock
  FROM public.huntly_quest_locks l
  WHERE l.id = v_lock_id;

  IF NOT FOUND THEN
    RETURN NULL;
  END IF;

  RETURN v_lock;
END;
$$;

REVOKE ALL ON FUNCTION public.scavenger_get_lock_for_target(text, uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.scavenger_get_lock_for_target(text, uuid) TO service_role;

CREATE OR REPLACE FUNCTION public.scavenger_is_play_unlocked(
  p_type text,
  p_item_id uuid
)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_lock public.huntly_quest_locks;
  v_row public.scavenger_unlocks;
  v_dual boolean;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  v_lock := public.scavenger_get_lock_for_target(p_type, p_item_id);

  -- No lock / not lockable => playable
  IF v_lock IS NULL THEN
    RETURN true;
  END IF;

  SELECT * INTO v_row
  FROM public.scavenger_unlocks u
  WHERE u.user_id = v_uid
    AND u.type = p_type
    AND u.item_id = p_item_id;

  IF NOT FOUND THEN
    RETURN false;
  END IF;

  -- Dual-lock (code + location): only a code unlock grants play access
  -- (matches Huntly unlockLogs.isPlayUnlocked).
  v_dual :=
    ('code' = ANY (v_lock.types))
    AND ('location' = ANY (v_lock.types));

  IF v_dual THEN
    RETURN v_row.unlock_source = 'code';
  END IF;

  RETURN true;
END;
$$;

REVOKE ALL ON FUNCTION public.scavenger_is_play_unlocked(text, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.scavenger_is_play_unlocked(text, uuid) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.scavenger_record_unlock(
  p_type text,
  p_item_id uuid,
  p_source text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_existing public.scavenger_unlocks;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  IF p_source IS NOT NULL AND p_source NOT IN ('code', 'location') THEN
    RAISE EXCEPTION 'Invalid unlock_source';
  END IF;

  SELECT * INTO v_existing
  FROM public.scavenger_unlocks u
  WHERE u.user_id = v_uid
    AND u.type = p_type
    AND u.item_id = p_item_id;

  IF FOUND THEN
    IF p_source = 'code' AND v_existing.unlock_source IS DISTINCT FROM 'code' THEN
      UPDATE public.scavenger_unlocks
      SET unlock_source = 'code'
      WHERE id = v_existing.id;
    END IF;
    RETURN;
  END IF;

  INSERT INTO public.scavenger_unlocks (user_id, type, item_id, unlock_source)
  VALUES (v_uid, p_type, p_item_id, p_source);
END;
$$;

REVOKE ALL ON FUNCTION public.scavenger_record_unlock(text, uuid, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.scavenger_record_unlock(text, uuid, text) TO service_role;

-- ═══════════════════════════════════════════════════════════════════════════
-- 5. Unlock RPCs (code / location) — Huntly parity
-- ═══════════════════════════════════════════════════════════════════════════

CREATE OR REPLACE FUNCTION public.scavenger_unlock_with_code(
  p_type text,
  p_item_id uuid,
  p_code text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_lock public.huntly_quest_locks;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  IF p_code IS NULL OR btrim(p_code) = '' THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'missing_code');
  END IF;

  v_lock := public.scavenger_get_lock_for_target(p_type, p_item_id);

  IF v_lock IS NULL THEN
    RETURN jsonb_build_object('ok', true, 'unlocked', true, 'reason', 'no_lock');
  END IF;

  IF NOT ('code' = ANY (v_lock.types)) THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'code_not_required');
  END IF;

  IF v_lock.code IS NULL OR lower(btrim(v_lock.code)) <> lower(btrim(p_code)) THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'incorrect_code');
  END IF;

  -- Dual-lock: replace any stale location unlock with a code unlock
  IF ('location' = ANY (v_lock.types)) THEN
    DELETE FROM public.scavenger_unlocks
    WHERE user_id = v_uid
      AND type = p_type
      AND item_id = p_item_id;
  END IF;

  PERFORM public.scavenger_record_unlock(p_type, p_item_id, 'code');

  RETURN jsonb_build_object(
    'ok', true,
    'unlocked', true,
    'play_unlocked', public.scavenger_is_play_unlocked(p_type, p_item_id)
  );
END;
$$;

REVOKE ALL ON FUNCTION public.scavenger_unlock_with_code(text, uuid, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.scavenger_unlock_with_code(text, uuid, text) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.scavenger_unlock_with_location(
  p_type text,
  p_item_id uuid,
  p_lat double precision,
  p_lng double precision
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_lock public.huntly_quest_locks;
  v_dist double precision;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  IF p_lat IS NULL OR p_lng IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'missing_coordinates');
  END IF;

  v_lock := public.scavenger_get_lock_for_target(p_type, p_item_id);

  IF v_lock IS NULL THEN
    RETURN jsonb_build_object('ok', true, 'unlocked', true, 'reason', 'no_lock');
  END IF;

  IF NOT ('location' = ANY (v_lock.types)) THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'location_not_required');
  END IF;

  IF v_lock.location_lat IS NULL OR v_lock.location_lng IS NULL OR v_lock.location_radius IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'lock_missing_location');
  END IF;

  v_dist := public.scavenger_distance_meters(
    p_lat, p_lng, v_lock.location_lat, v_lock.location_lng
  );

  IF v_dist > v_lock.location_radius THEN
    RETURN jsonb_build_object(
      'ok', false,
      'reason', 'out_of_range',
      'distance_meters', v_dist,
      'radius_meters', v_lock.location_radius
    );
  END IF;

  PERFORM public.scavenger_record_unlock(p_type, p_item_id, 'location');

  RETURN jsonb_build_object(
    'ok', true,
    'unlocked', true,
    'play_unlocked', public.scavenger_is_play_unlocked(p_type, p_item_id),
    'distance_meters', v_dist
  );
END;
$$;

REVOKE ALL ON FUNCTION public.scavenger_unlock_with_location(text, uuid, double precision, double precision)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.scavenger_unlock_with_location(text, uuid, double precision, double precision)
  TO authenticated, service_role;

