-- Club feed: mix approved real photos with temporary submission photos.
-- Temporary photo_ids are negative (-temporary_submission_photos.id) to avoid collisions.
CREATE OR REPLACE FUNCTION public.get_random_club_photos(
  p_count integer DEFAULT 6,
  p_exclude_ids bigint[] DEFAULT '{}'
)
RETURNS TABLE (
  photo_id bigint,
  photo_url text,
  profile_id bigint,
  activity_title text,
  nickname text,
  team_name text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  WITH real_pool AS (
    SELECT
      p.photo_id,
      p.photo_url,
      p.profile_id,
      p.activity_id,
      NULL::text AS nickname,
      NULL::text AS team_name,
      false AS is_temp
    FROM public.user_activity_photos p
    WHERE p.status = 1
      AND p.activity_id IS NOT NULL
      AND (
        cardinality(p_exclude_ids) = 0
        OR NOT (p.photo_id = ANY (p_exclude_ids))
      )
    ORDER BY p.photo_id DESC
    LIMIT GREATEST(p_count * 12, 72)
  ),
  temp_pool AS (
    SELECT
      (-tp.id)::bigint AS photo_id,
      tp.photo_url,
      NULL::bigint AS profile_id,
      ts.activity_id,
      ts.display_name AS nickname,
      lower(t.name::text) AS team_name,
      true AS is_temp
    FROM public.temporary_submission_photos tp
    INNER JOIN public.temporary_submissions ts ON ts.id = tp.temporary_submission_id
    INNER JOIN public.teams t ON t.id = ts.team_id
    WHERE (
      cardinality(p_exclude_ids) = 0
      OR NOT ((-tp.id)::bigint = ANY (p_exclude_ids))
    )
    ORDER BY tp.id DESC
    LIMIT GREATEST(p_count * 12, 72)
  ),
  pool AS (
    SELECT * FROM real_pool
    UNION ALL
    SELECT * FROM temp_pool
  ),
  picked AS (
    SELECT *
    FROM pool
    ORDER BY random()
    LIMIT GREATEST(p_count, 0)
  )
  SELECT
    pk.photo_id,
    pk.photo_url,
    pk.profile_id,
    COALESCE(a.title, '')::text AS activity_title,
    CASE
      WHEN pk.is_temp THEN COALESCE(pk.nickname, '')::text
      ELSE COALESCE(pp.nickname, '')::text
    END AS nickname,
    CASE
      WHEN pk.is_temp THEN COALESCE(pk.team_name, '')::text
      ELSE COALESCE(lower(pp.team_name::text), '')::text
    END AS team_name
  FROM picked pk
  LEFT JOIN public.activities a ON a.id = pk.activity_id
  LEFT JOIN public.profile_public pp ON pp.id = pk.profile_id;
$$;

GRANT EXECUTE ON FUNCTION public.get_random_club_photos(integer, bigint[]) TO authenticated;
GRANT EXECUTE ON FUNCTION public.get_random_club_photos(integer, bigint[]) TO service_role;
