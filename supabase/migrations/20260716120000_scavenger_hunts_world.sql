CREATE OR REPLACE FUNCTION public.scavenger_ensure_quest_state(
  p_profile_id bigint,
  p_quest_id uuid
)
RETURNS public.scavenger_quest_states
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_state public.scavenger_quest_states;
  v_published boolean;
BEGIN
  PERFORM public.scavenger_assert_profile_owner(p_profile_id);

  SELECT q.published INTO v_published
  FROM public.huntly_quests q
  WHERE q.id = p_quest_id;

  IF NOT FOUND OR NOT coalesce(v_published, false) THEN
    RAISE EXCEPTION 'Quest not found or not published';
  END IF;

  SELECT * INTO v_state
  FROM public.scavenger_quest_states s
  WHERE s.profile_id = p_profile_id
    AND s.quest_id = p_quest_id;

  IF FOUND THEN
    RETURN v_state;
  END IF;

  INSERT INTO public.scavenger_quest_states (profile_id, quest_id)
  VALUES (p_profile_id, p_quest_id)
  RETURNING * INTO v_state;

  RETURN v_state;
END;
$$;

REVOKE ALL ON FUNCTION public.scavenger_ensure_quest_state(bigint, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.scavenger_ensure_quest_state(bigint, uuid) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.scavenger_mark_item_found(
  p_profile_id bigint,
  p_item_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_item public.huntly_quest_items;
  v_quest public.huntly_quests;
  v_state public.scavenger_quest_states;
  v_total integer;
  v_found uuid[];
BEGIN
  PERFORM public.scavenger_assert_profile_owner(p_profile_id);

  SELECT * INTO v_item
  FROM public.huntly_quest_items i
  WHERE i.id = p_item_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Quest item not found';
  END IF;

  SELECT * INTO v_quest
  FROM public.huntly_quests q
  WHERE q.id = v_item.quest_id;

  IF NOT FOUND OR NOT coalesce(v_quest.published, false) THEN
    RAISE EXCEPTION 'Quest not found or not published';
  END IF;

  IF NOT public.scavenger_is_play_unlocked('quest', v_quest.id) THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'not_unlocked');
  END IF;

  -- Trivia items must go through scavenger_validate_item_answer
  IF v_item.question IS NOT NULL AND btrim(v_item.question) <> '' THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'requires_answer');
  END IF;

  v_state := public.scavenger_ensure_quest_state(p_profile_id, v_quest.id);

  IF p_item_id = ANY (v_state.found_items) THEN
    RETURN jsonb_build_object(
      'ok', true,
      'already_found', true,
      'found_items', to_jsonb(v_state.found_items),
      'complete', v_state.complete
    );
  END IF;

  v_found := array_append(v_state.found_items, p_item_id);

  SELECT count(*)::integer INTO v_total
  FROM public.huntly_quest_items i
  WHERE i.quest_id = v_quest.id;

  UPDATE public.scavenger_quest_states
  SET
    found_items = v_found,
    complete = (cardinality(v_found) >= v_total AND v_total > 0),
    updated_at = now()
  WHERE id = v_state.id
  RETURNING * INTO v_state;

  RETURN jsonb_build_object(
    'ok', true,
    'already_found', false,
    'found_items', to_jsonb(v_state.found_items),
    'complete', v_state.complete
  );
END;
$$;

REVOKE ALL ON FUNCTION public.scavenger_mark_item_found(bigint, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.scavenger_mark_item_found(bigint, uuid) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.scavenger_validate_item_answer(
  p_profile_id bigint,
  p_item_id uuid,
  p_answer text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_item public.huntly_quest_items;
  v_quest public.huntly_quests;
  v_state public.scavenger_quest_states;
  v_has_question boolean;
  v_correct boolean;
  v_found uuid[];
  v_total integer;
BEGIN
  PERFORM public.scavenger_assert_profile_owner(p_profile_id);

  IF p_answer IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'missing_answer');
  END IF;

  IF char_length(p_answer) > 1000 THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'answer_too_long');
  END IF;

  SELECT * INTO v_item
  FROM public.huntly_quest_items i
  WHERE i.id = p_item_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Quest item not found';
  END IF;

  SELECT * INTO v_quest
  FROM public.huntly_quests q
  WHERE q.id = v_item.quest_id;

  IF NOT FOUND OR NOT coalesce(v_quest.published, false) THEN
    RAISE EXCEPTION 'Quest not found or not published';
  END IF;

  IF NOT public.scavenger_is_play_unlocked('quest', v_quest.id) THEN
    RETURN jsonb_build_object('ok', false, 'reason', 'not_unlocked');
  END IF;

  v_has_question := v_item.question IS NOT NULL AND btrim(v_item.question) <> '';

  IF NOT v_has_question THEN
    RETURN jsonb_build_object(
      'ok', true,
      'is_correct', false,
      'has_question', false,
      'item_marked_as_found', false
    );
  END IF;

  v_correct :=
    lower(btrim(coalesce(v_item.answer, ''))) = lower(btrim(p_answer));

  IF NOT v_correct THEN
    RETURN jsonb_build_object(
      'ok', true,
      'is_correct', false,
      'has_question', true,
      'item_marked_as_found', false
    );
  END IF;

  v_state := public.scavenger_ensure_quest_state(p_profile_id, v_quest.id);

  IF p_item_id = ANY (v_state.found_items) THEN
    RETURN jsonb_build_object(
      'ok', true,
      'is_correct', true,
      'has_question', true,
      'item_marked_as_found', true,
      'already_found', true,
      'complete', v_state.complete
    );
  END IF;

  v_found := array_append(v_state.found_items, p_item_id);

  SELECT count(*)::integer INTO v_total
  FROM public.huntly_quest_items i
  WHERE i.quest_id = v_quest.id;

  UPDATE public.scavenger_quest_states
  SET
    found_items = v_found,
    complete = (cardinality(v_found) >= v_total AND v_total > 0),
    updated_at = now()
  WHERE id = v_state.id
  RETURNING * INTO v_state;

  RETURN jsonb_build_object(
    'ok', true,
    'is_correct', true,
    'has_question', true,
    'item_marked_as_found', true,
    'already_found', false,
    'found_items', to_jsonb(v_state.found_items),
    'complete', v_state.complete
  );
END;
$$;

REVOKE ALL ON FUNCTION public.scavenger_validate_item_answer(bigint, uuid, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.scavenger_validate_item_answer(bigint, uuid, text) TO authenticated, service_role;

-- ═══════════════════════════════════════════════════════════════════════════
-- 7. End session → user_achievements (unpaid finds × 5)
-- ═══════════════════════════════════════════════════════════════════════════

CREATE OR REPLACE FUNCTION public.scavenger_end_session(
  p_profile_id bigint,
  p_quest_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid;
  v_state public.scavenger_quest_states;
  v_team_id bigint;
  v_unpaid uuid[];
  v_n integer;
  v_xp integer;
  v_message text;
  v_achievement_id bigint;
BEGIN
  v_uid := public.scavenger_assert_profile_owner(p_profile_id);

  SELECT * INTO v_state
  FROM public.scavenger_quest_states s
  WHERE s.profile_id = p_profile_id
    AND s.quest_id = p_quest_id;

  IF NOT FOUND THEN
    RETURN jsonb_build_object(
      'ok', true,
      'awarded', false,
      'items_found_this_session', 0,
      'xp', 0
    );
  END IF;

  SELECT ARRAY(
    SELECT x
    FROM unnest(v_state.found_items) AS x
    WHERE NOT (x = ANY (v_state.items_rewarded))
  ) INTO v_unpaid;

  v_n := coalesce(cardinality(v_unpaid), 0);

  IF v_n = 0 THEN
    RETURN jsonb_build_object(
      'ok', true,
      'awarded', false,
      'items_found_this_session', 0,
      'xp', 0,
      'quest_state_id', v_state.id,
      'complete', v_state.complete
    );
  END IF;

  SELECT ud.team INTO v_team_id
  FROM public.user_data ud
  WHERE ud.user_id = v_uid;

  IF v_team_id IS NULL THEN
    RAISE EXCEPTION 'User has no team; cannot award scavenger XP';
  END IF;

  v_xp := v_n * 5;
  v_message := format('Hunt session: found %s items.', v_n);

  INSERT INTO public.user_achievements (
    profile_id,
    team_id,
    source,
    source_id,
    message,
    xp
  ) VALUES (
    p_profile_id,
    v_team_id,
    'scavenger',
    v_state.id,
    v_message,
    v_xp
  )
  RETURNING id INTO v_achievement_id;

  UPDATE public.scavenger_quest_states
  SET
    items_rewarded = (
      SELECT ARRAY(
        SELECT DISTINCT x
        FROM unnest(v_state.items_rewarded || v_unpaid) AS x
      )
    ),
    updated_at = now()
  WHERE id = v_state.id
  RETURNING * INTO v_state;

  RETURN jsonb_build_object(
    'ok', true,
    'awarded', true,
    'items_found_this_session', v_n,
    'item_ids', to_jsonb(v_unpaid),
    'xp', v_xp,
    'achievement_id', v_achievement_id,
    'quest_state_id', v_state.id,
    'complete', v_state.complete,
    'message', v_message
  );
END;
$$;

REVOKE ALL ON FUNCTION public.scavenger_end_session(bigint, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.scavenger_end_session(bigint, uuid) TO authenticated, service_role;

-- Discard in-progress session photos for a profile/quest (Huntly end-session discard).
CREATE OR REPLACE FUNCTION public.scavenger_discard_session_photos(
  p_profile_id bigint,
  p_quest_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
