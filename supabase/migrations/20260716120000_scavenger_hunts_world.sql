-- Group completion status (Huntly: all member quests fully found + optional CTA).
CREATE OR REPLACE FUNCTION public.scavenger_group_completion_status(
  p_profile_id bigint,
  p_group_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_published boolean;
  v_on_completion jsonb;
  v_all_completed boolean;
  v_quest_count integer;
BEGIN
  PERFORM public.scavenger_assert_profile_owner(p_profile_id);

  SELECT g.published, g.on_completion
  INTO v_published, v_on_completion
  FROM public.huntly_quest_groups g
  WHERE g.id = p_group_id;

  IF NOT FOUND OR NOT coalesce(v_published, false) THEN
    RAISE EXCEPTION 'Quest group not found or not published';
  END IF;

  SELECT count(*)::integer INTO v_quest_count
  FROM public.huntly_quests q
  WHERE q.group_id = p_group_id
    AND q.published = true;

  IF v_quest_count = 0 THEN
    v_all_completed := false;
  ELSE
    SELECT bool_and(completed) INTO v_all_completed
    FROM (
      SELECT
        (
          SELECT count(*) FROM public.huntly_quest_items i WHERE i.quest_id = q.id
        ) > 0
        AND (
          SELECT count(*) FROM public.huntly_quest_items i WHERE i.quest_id = q.id
        ) = coalesce(
          (
            SELECT cardinality(s.found_items)
            FROM public.scavenger_quest_states s
            WHERE s.profile_id = p_profile_id
              AND s.quest_id = q.id
          ),
          0
        ) AS completed
      FROM public.huntly_quests q
      WHERE q.group_id = p_group_id
        AND q.published = true
    ) t;
  END IF;

  RETURN jsonb_build_object(
    'ok', true,
    'all_completed', coalesce(v_all_completed, false),
    'has_cta', (v_on_completion IS NOT NULL AND v_on_completion ? 'cta'),
    'on_completion', v_on_completion,
    'quest_count', v_quest_count
  );
END;
$$;

REVOKE ALL ON FUNCTION public.scavenger_group_completion_status(bigint, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.scavenger_group_completion_status(bigint, uuid) TO authenticated, service_role;
