-- Huntly World scavenger hunts: consume published huntly_* catalog, World-owned
-- progress/XP/photos. Secrets (lock codes, trivia answers) stay off the client;
-- unlock / validate / end-session go through SECURITY DEFINER RPCs.
--
-- Postgres 15+ (supabase/config.toml). Patterns from Supabase docs:
-- - SET search_path on SECURITY DEFINER functions
-- - auth.uid() ownership checks inside definers
-- - REVOKE EXECUTE FROM PUBLIC/anon; GRANT TO authenticated
-- - Catalog via security_barrier views that omit secrets (base huntly_* stay
--   service-role only for the Huntly Express API)
--
-- Client-facing surface (mobile later):
--   Views:  scavenger_quests_public, scavenger_quest_groups_public,
--           scavenger_quest_items_public, scavenger_quest_locks_public
--   Tables: scavenger_quest_states (SELECT), scavenger_unlocks (SELECT),
--           scavenger_session_photos (SELECT/INSERT/DELETE)
--   Storage bucket: scavenger-photos (path prefix = auth.uid())
--   RPCs:
--     scavenger_is_play_unlocked(type, item_id)
--     scavenger_unlock_with_code(type, item_id, code)
--     scavenger_unlock_with_location(type, item_id, lat, lng)
--     scavenger_ensure_quest_state(profile_id, quest_id)
--     scavenger_mark_item_found(profile_id, item_id)
--     scavenger_validate_item_answer(profile_id, item_id, answer)
--     scavenger_end_session(profile_id, quest_id)  -- XP = unpaid finds × 5
--     scavenger_discard_session_photos(profile_id, quest_id)
--     scavenger_group_completion_status(profile_id, group_id)
--   type = 'quest' | 'questGroup'
--   user_achievements: source='scavenger', source_id=scavenger_quest_states.id,
--     message='Hunt session: found N items.'

